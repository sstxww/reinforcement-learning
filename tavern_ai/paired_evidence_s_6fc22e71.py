"""Strict paired full-match evidence comparison; no score promotion or model writes.

This is an opt-in additive gate, not a substitute for playing real TavernGym.
Use real completed receipts generated by the exact evaluated policy.
"""
from __future__ import annotations

import argparse
import json
import math
import random
from pathlib import Path
from statistics import mean

PINNED_SOURCE = "6d8712c93022ba11"
PINNED_VERSION = "1.1.0"
GUARD_KEYS = ("guard_interventions", "model_guard_forced_end",
              "safety_fallback_count", "baseline_fallback_actions")


def _whole(value, field: str, minimum: int = 0) -> int:
    if type(value) is not int or value < minimum:
        raise ValueError(f"Invalid {field}: expected integer >= {minimum}")
    return value


def _records(rows: list[dict], *, candidate: bool) -> dict[tuple[int, int], dict]:
    if not isinstance(rows, list) or not rows:
        raise ValueError("Require at least one real full-match receipt per arm")
    result = {}
    for row in rows:
        if not isinstance(row, dict) or row.get("environment") != "TavernGym":
            raise ValueError("Only TavernGym receipts are comparable")
        if row.get("completed") is not True or row.get("turn_limit_end") is not False:
            raise ValueError("Incomplete/turn-limit match is not a rank result")
        if row.get("truncated_combats") != 0 or type(row.get("truncated_combats")) is not int:
            raise ValueError("Combat-truncated game is not eligible")
        if row.get("engine_version") != PINNED_VERSION or row.get("engine_source_hash") != PINNED_SOURCE:
            raise ValueError("TavernGym engine mismatch")
        seat = _whole(row.get("seat", 0), "controlled seat")
        if seat > 7:
            raise ValueError("Controlled seat must be 0..7")
        key = (_whole(row.get("seed"), "seed"), seat)
        if key in result:
            raise ValueError("Duplicate seed and controlled seat would overcount games")
        places = row.get("placements")
        if type(places) is not list or len(places) != 8 or any(type(x) is not int for x in places):
            raise ValueError("Invalid eight-seat placements")
        if sorted(places) != list(range(1, 9)):
            raise ValueError("Eight ranks must form a complete permutation")
        _whole(row.get("turns"), "turns", 1)
        _whole(row.get("decisions"), "decisions", 1)
        expected = "model" if candidate else "baseline"
        if row.get("policy") != expected:
            raise ValueError(f"Expected {expected} policy in corresponding arm")
        if candidate:
            digest = row.get("model_sha256")
            if not isinstance(digest, str) or len(digest) != 64 or any(x not in "0123456789abcdef" for x in digest):
                raise ValueError("Model receipt lacks full SHA256")
        result[key] = row
    return result


def _guard_state(row: dict) -> tuple[str, int | None]:
    """No raw-policy claim without BOTH a raw variant label and zero counters.

    A model receipt alone does not disclose whether its driver applied a rule.
    Treat any unrecognized variant as unknown, and known assisted variants as
    guarded even if their rules happened not to fire in this game.
    """
    reported = []
    for key in GUARD_KEYS:
        if key in row:
            reported.append(_whole(row[key], key))
    maximum = max(reported) if reported else None
    variant = row.get("policy_variant")
    if variant is not None and (type(variant) is not str or not variant.strip()):
        raise ValueError("Invalid policy_variant")
    if any(x > 0 for x in reported):
        return "guarded", maximum
    if isinstance(variant, str) and any(
        marker in variant.lower() for marker in ("guard", "override", "fallback", "hybrid", "rule_assist")
    ):
        return "guarded", maximum
    if variant not in {"raw_ppo_model", "raw_model", "model_without_fallback"} or not reported:
        return "unknown", maximum
    return "explicit_zero", maximum


def _bootstrap(values: list[int], *, seed: int, draws: int = 4000) -> list[float]:
    rng = random.Random(seed)
    n = len(values)
    ordered = sorted(sum(values[rng.randrange(n)] for _ in range(n)) / n for _ in range(draws))
    return [ordered[math.floor((draws - 1) * .025)],
            ordered[math.ceil((draws - 1) * .975)]]


def compare(candidate: list[dict], baseline: list[dict], *, seed: int = 20261102) -> dict:
    """Paired on both engine seed AND controlled seat; no pseudo-replication by action."""
    _whole(seed, "bootstrap seed")
    c = _records(candidate, candidate=True)
    b = _records(baseline, candidate=False)
    if set(c) != set(b):
        raise ValueError("Paired arms require identical seed+seat combinations")
    model_hashes = {row["model_sha256"] for row in c.values()}
    if len(model_hashes) != 1:
        raise ValueError("Cannot mix checkpoint identities in one candidate arm")
    pairs = sorted(c)
    candidate_ranks = [c[key]["placements"][key[1]] for key in pairs]
    baseline_ranks = [b[key]["placements"][key[1]] for key in pairs]
    diffs = [a - z for a, z in zip(candidate_ranks, baseline_ranks)]
    guards = [_guard_state(c[key]) for key in pairs]
    states = [s for s, _ in guards]
    status = "explicit_no_fallback" if all(s == "explicit_zero" for s in states) else (
        "guarded" if any(s == "guarded" for s in states) else "guard_status_unknown")
    return {
        "schema": 1,
        "engine": {"version": PINNED_VERSION, "source_hash": PINNED_SOURCE},
        "model_sha256": next(iter(model_hashes)), "games_per_arm": len(pairs),
        "seed_seat_pairs": [{"seed": s, "seat": seat} for s, seat in pairs],
        "candidate_ranks": candidate_ranks, "baseline_ranks": baseline_ranks,
        "candidate_mean_rank": mean(candidate_ranks), "baseline_mean_rank": mean(baseline_ranks),
        "candidate_top4_rate": sum(v <= 4 for v in candidate_ranks) / len(pairs),
        "candidate_first_place_rate": sum(v == 1 for v in candidate_ranks) / len(pairs),
        "candidate_minus_baseline_mean_rank": mean(diffs),
        "paired_mean_rank_delta_bootstrap_95pct": _bootstrap(diffs, seed=seed),
        "guard_evidence": status,
        "reported_guard_interventions_max_per_game": [g for _, g in guards],
        "guard_status_unknown_games": states.count("unknown"),
        "complete_match_rate": 1.0,
        "eligible_for_raw_model_claim": status == "explicit_no_fallback",
        "champion_promoted": False,
        "promotion_decision": "not_evaluated",
        "warning": (
            "All results descriptive. Rank lower is better; same-seed/seat sampling "
            "is paired, actions within a game are not independent. Explicit zero guard "
            "counters alone do not establish strategic strength or optimizer resumability."
        ),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidate", type=Path, nargs="+", required=True)
    parser.add_argument("--baseline", type=Path, nargs="+", required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--bootstrap-seed", type=int, default=20261102)
    args = parser.parse_args()
    c = [json.loads(p.read_text(encoding="utf-8")) for p in args.candidate]
    b = [json.loads(p.read_text(encoding="utf-8")) for p in args.baseline]
    summary = compare(c, b, seed=args.bootstrap_seed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main()
